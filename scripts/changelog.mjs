#!/usr/bin/env node
// Build and InBul bookkeeping for Dukaan Dost. See MD/project_docs_guide.md.
//
//   node scripts/changelog.mjs --pending "<title>" "<summary>" --why "..." --verified "..." --next "..."
//       Write (or refresh) MD/builds/build-N.md for the next build and regenerate CHANGELOG.md.
//       Run AFTER `git add`-ing the change files: the "Files changed" list reads the staged diff.
//       The hand-written part of an existing report is never overwritten.
//   node scripts/changelog.mjs --tag
//       Pin HEAD: `build-N` for a build commit, `InBulNN` for a commit titled "InBulNN: ...".
//       Doesn't modify files.
//   node scripts/changelog.mjs --next-internal
//       Print the next InBul id.
//   node scripts/changelog.mjs --rebuild
//       Rebuild every report's "Files changed" list from git, and CHANGELOG.md.

import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const BUILDS_DIR = join(ROOT, "MD", "builds");
const CHANGELOG = join(ROOT, "CHANGELOG.md");
const FIRST_BUILD = 1000;
const FILES_MARKER =
  "<!-- Everything below is rebuilt from git by scripts/changelog.mjs. Edit above this line only. -->";

const git = (...args) =>
  execFileSync("git", args, { cwd: ROOT, encoding: "utf8" }).replace(/\r\n/g, "\n").trimEnd();

const fail = (msg) => {
  console.error(`changelog: ${msg}`);
  process.exit(1);
};

const tags = () => (git("tag", "--list").split("\n").filter(Boolean));

function buildTags() {
  return tags()
    .map((t) => /^build-(\d+)$/.exec(t))
    .filter(Boolean)
    .map((m) => Number(m[1]))
    .sort((a, b) => a - b);
}

function nextBuild() {
  const b = buildTags();
  return b.length ? b[b.length - 1] + 1 : FIRST_BUILD;
}

function nextInternal() {
  const nums = tags()
    .map((t) => /^InBul(\d+)$/.exec(t))
    .filter(Boolean)
    .map((m) => Number(m[1]));
  const n = nums.length ? Math.max(...nums) + 1 : 1;
  return `InBul${String(n).padStart(2, "0")}`;
}

const reportPath = (n) => join(BUILDS_DIR, `build-${n}.md`);

// Files the bookkeeping itself writes; never listed as "changed".
const isBookkeeping = (path) => path === "CHANGELOG.md" || path.startsWith("MD/builds/");

function formatFiles(nameStatus) {
  const lines = nameStatus
    .split("\n")
    .filter(Boolean)
    .map((l) => l.split("\t"))
    .filter((parts) => !isBookkeeping(parts[parts.length - 1]))
    .map(([status, ...paths]) => `- \`${status[0]}\` ${paths.join(" → ")}`);
  return lines.length ? lines.join("\n") : "_No files._";
}

function stagedFiles() {
  return formatFiles(git("diff", "--cached", "--name-status"));
}

function taggedFiles(n) {
  return formatFiles(git("show", "--name-status", "--format=", `build-${n}`));
}

function writeFilesSection(n, filesList) {
  const path = reportPath(n);
  const text = readFileSync(path, "utf8").replace(/\r\n/g, "\n");
  const i = text.indexOf(FILES_MARKER);
  const hand = (i === -1 ? text : text.slice(0, i)).trimEnd();
  writeFileSync(path, `${hand}\n\n${FILES_MARKER}\n## Files changed\n${filesList}\n`);
}

function parseReport(n) {
  const text = readFileSync(reportPath(n), "utf8").replace(/\r\n/g, "\n");
  const title = (/^# Build \d+: (.+)$/m.exec(text) || [])[1] || "(untitled)";
  const summary = ((/## What changed\n([\s\S]*?)(\n## |\n<!--|$)/.exec(text) || [])[1] || "").trim();
  const date = (/^\*\*Date:\*\* (\S+)$/m.exec(text) || [])[1] || "";
  return { title, summary, date };
}

function writeChangelog() {
  const tagged = new Set(buildTags());
  const reports = existsSync(BUILDS_DIR)
    ? readdirSync(BUILDS_DIR)
        .map((f) => /^build-(\d+)\.md$/.exec(f))
        .filter(Boolean)
        .map((m) => Number(m[1]))
        .sort((a, b) => b - a)
    : [];
  const entries = reports.map((n) => {
    // An untagged report is the build being committed right now, so its
    // own date is what the committed CHANGELOG should show.
    const { title, summary, date } = parseReport(n);
    const when = tagged.has(n) ? git("log", "-1", "--format=%as", `build-${n}`) : date;
    return `## Build ${n} · ${when}\n**${title}**\n\n${summary}\n\n[Report](MD/builds/build-${n}.md)`;
  });
  const head =
    "# Changelog\n\n" +
    "User-visible builds of Dukaan Dost, newest first. Generated by `scripts/changelog.mjs` " +
    "from git tags and `MD/builds/`; don't edit by hand. Internal changes (InBuls) aren't listed.";
  writeFileSync(CHANGELOG, [head, ...entries].join("\n\n") + "\n");
}

function argValue(args, flag) {
  const i = args.indexOf(flag);
  return i === -1 ? "" : args[i + 1] || "";
}

function pending(args) {
  const [title, summary] = args.filter((a, i) => !a.startsWith("--") && !args[i - 1]?.startsWith("--"));
  if (!title || !summary) fail('usage: --pending "<title>" "<summary>" --why "..." --verified "..." --next "..."');
  if (/\(Build \d+\)/i.test(title)) fail('never put "(Build N)" in a title; the tag carries the number');

  const n = nextBuild();
  mkdirSync(BUILDS_DIR, { recursive: true });
  if (!existsSync(reportPath(n))) {
    const today = new Date().toISOString().slice(0, 10);
    const section = (h, body) => `## ${h}\n${body || "_To fill in._"}\n`;
    writeFileSync(
      reportPath(n),
      [
        `# Build ${n}: ${title}\n`,
        `**Date:** ${today}\n`,
        section("What changed", summary),
        section("Why", argValue(args, "--why")),
        section("How it was verified", argValue(args, "--verified")),
        section("What to improve next", argValue(args, "--next")),
      ].join("\n")
    );
    console.log(`Wrote MD/builds/build-${n}.md`);
  } else {
    console.log(`MD/builds/build-${n}.md already exists; kept its hand-written part`);
  }
  writeFilesSection(n, stagedFiles());
  for (const t of buildTags()) if (existsSync(reportPath(t))) writeFilesSection(t, taggedFiles(t));
  writeChangelog();
  console.log(`Next: git add MD/builds CHANGELOG.md, commit with the title "${title}", then --tag`);
}

function tag() {
  if (git("tag", "--points-at", "HEAD")) fail(`HEAD is already tagged (${git("tag", "--points-at", "HEAD")})`);
  const subject = git("log", "-1", "--format=%s");
  const inbul = /^(InBul\d+):/.exec(subject);
  if (inbul) {
    if (tags().includes(inbul[1])) fail(`${inbul[1]} already exists; the next free id is ${nextInternal()}`);
    git("tag", inbul[1]);
    console.log(`Tagged HEAD as ${inbul[1]}`);
    return;
  }
  const n = nextBuild();
  if (!existsSync(reportPath(n))) fail(`no MD/builds/build-${n}.md; run --pending before committing a build`);
  const { title } = parseReport(n);
  if (title !== subject) fail(`commit title "${subject}" doesn't match build-${n}'s title "${title}"`);
  git("tag", `build-${n}`);
  console.log(`Tagged HEAD as build-${n}`);
}

function rebuild() {
  for (const t of buildTags()) if (existsSync(reportPath(t))) writeFilesSection(t, taggedFiles(t));
  writeChangelog();
  console.log("Rebuilt the report file lists and CHANGELOG.md");
}

const args = process.argv.slice(2);
if (args.includes("--pending")) pending(args.filter((a) => a !== "--pending"));
else if (args.includes("--tag")) tag();
else if (args.includes("--next-internal")) console.log(nextInternal());
else if (args.includes("--rebuild")) rebuild();
else fail("expected one of --pending, --tag, --next-internal, --rebuild");
